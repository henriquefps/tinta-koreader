local T = ...
local F = require("core/format")
local I18n = require("core/i18n")
local eq, same, check = T.eq, T.same, T.check
I18n.set_lang("pt")

local t = T.utc(2026, 10, 16, 9, 5)
eq("format: hm", F.hm(t, T.date), "09:05")
eq("format: utc_date helper", F.hm(t, F.utc_date), "09:05")
eq("format: minute_of_day", F.minute_of_day(t, T.date), 545)
eq("format: parse_hm", F.parse_hm("07:30"), 450)
eq("format: parse_hm 7:05", F.parse_hm("7:05"), 425)
eq("format: parse_hm bad hour", F.parse_hm("24:00"), nil)
eq("format: parse_hm bad min", F.parse_hm("10:60"), nil)
eq("format: parse_hm junk", F.parse_hm("ab"), nil)
eq("format: parse_hm nil", F.parse_hm(nil), nil)
eq("format: hm_from_minutes", F.hm_from_minutes(450), "07:30")
eq("format: hm_from_minutes wraps", F.hm_from_minutes(1440 + 5), "00:05")

eq("format: ago nil", F.ago(nil, t), "")
eq("format: ago now", F.ago(t - 59, t), "agora")
eq("format: ago min", F.ago(t - 180, t), "há 3 min")
eq("format: ago h", F.ago(t - 7300, t), "há 2 h")
eq("format: ago d", F.ago(t - 3 * 86400, t), "há 3 d")
eq("format: ago future -> agora", F.ago(t + 50, t), "agora")

eq("format: every nil", F.every(nil), "")
eq("format: every manual", F.every(0), "manual")
eq("format: every 30 s", F.every(30), "a cada 30 s")
eq("format: every 1 min", F.every(60), "a cada 1 min")
eq("format: every 15 min", F.every(900), "a cada 15 min")
eq("format: every 1 h", F.every(3600), "a cada 1 h")

eq("format: eta 25min", F.eta(25 / 60), "~25min")
eq("format: eta rounds to 5", F.eta(23 / 60), "~25min")
eq("format: eta min 5", F.eta(1 / 60), "~5min")
eq("format: eta 4h20", F.eta(4 + 20 / 60), "~4h20")
eq("format: eta 1h05", F.eta(1 + 5 / 60), "~1h05")
eq("format: eta 12h", F.eta(12.4), "~12h")
eq("format: eta nil", F.eta(nil), nil)
eq("format: eta negative", F.eta(-1), nil)

eq("format: battery", F.battery(82, false, "~17h"), "82% · ~17h")
eq("format: battery charging", F.battery(82, true, "~40min"), "⚡ 82% · ~40min")
eq("format: battery no eta", F.battery(81.6, false), "82%")

eq("format: utf8_len ascii", F.utf8_len("abc"), 3)
eq("format: utf8_len accents", F.utf8_len("Notificações"), 12)
eq("format: utf8_len emoji/symbols", F.utf8_len("⚡…"), 2)
eq("format: utf8_head", F.utf8_head("Notificações", 9), "Notificaç")
eq("format: utf8_head all", F.utf8_head("ab", 5), "ab")
eq("format: utf8_head 0", F.utf8_head("ab", 0), "")
eq("format: truncate fits", F.truncate("Pilha", 5), "Pilha")
eq("format: truncate cuts with …", F.truncate("Notificações", 8), "Notific…")
eq("format: truncate never splits a char", F.truncate("ãããããã", 4), "ããã…")
eq("format: truncate trims space", F.truncate("ab cd", 4), "ab…")
eq("format: truncate 1", F.truncate("abc", 1), "…")
eq("format: truncate nil", F.truncate(nil, 3), "")
eq("format: truncate no max", F.truncate("abc"), "abc")

eq("format: window weekdays", F.window_text({ from = "07:30", to = "18:30", weekdays = true }), "dias úteis 07:30–18:30")
eq("format: window all", F.window_text({ from = "07:30", to = "18:30" }), "07:30–18:30")
eq("format: window nil", F.window_text(nil), "")

-- R-W4 footer, wide and narrow
local now = t
same("footer: ok wide", F.footer({ kind = "ok", last_ok = now - 180, interval = 60 }, false, now), { "há 3 min", "a cada 1 min" })
same("footer: ok narrow", F.footer({ kind = "ok", last_ok = now - 180, interval = 60 }, true, now), { "há 3 min" })
same("footer: failed wide", F.footer({ kind = "failed", last_ok = now - 600 }, false, now), { "sem resposta", "há 10 min" })
same("footer: failed narrow", F.footer({ kind = "failed", last_ok = now - 600 }, true, now), { "sem resposta" })
same("footer: paused wide", F.footer({ kind = "paused", last_ok = now - 600, resume = "07:30" }, false, now), { "há 10 min", "volta 07:30" })
same("footer: paused narrow", F.footer({ kind = "paused", resume = "07:30" }, true, now), { "volta 07:30" })
same("footer: busy", F.footer({ kind = "busy" }, false, now), { "atualizando…" })
same("footer: busy narrow", F.footer({ kind = "busy" }, true, now), { "atualizando…" })
same("footer: none", F.footer({ kind = "none" }, false, now), { "configurações" })
same("footer: error", F.footer({ kind = "error", last_ok = now - 60 }, false, now), { "erro na app", "há 1 min" })
eq("header: ok", F.header({ kind = "ok", last_ok = now - 180, interval = 60 }, now), "há 3 min · a cada 1 min")
eq("header: paused", F.header({ kind = "paused", resume = "07:30" }, now), "pausado até 07:30")
eq("header: error (R-E4)", F.header({ kind = "error" }, now), "erro na app")
eq("header: stale (R-S5)", F.header({ kind = "failed", last_ok = now - 600 }, now), "sem resposta · último dado há 10 min")
eq("header: failed no data", F.header({ kind = "failed" }, now), "sem resposta")
eq("header: busy", F.header({ kind = "busy" }, now), "atualizando…")
